-- EXTENSIONES
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. TABLAS GEOGRAFICAS
CREATE TABLE IF NOT EXISTS countries (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    name_country VARCHAR(100) NOT NULL,
    code_country VARCHAR(10) NOT NULL UNIQUE,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    telephone_prefix VARCHAR(10),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS state_regions (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    name_region VARCHAR(100) NOT NULL,
    code_region VARCHAR(20) NOT NULL,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    country_id UUID NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_state_regions_country FOREIGN KEY (country_id) REFERENCES countries (id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS city_municipalities (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    name_city VARCHAR(100) NOT NULL,
    code_city VARCHAR(20) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    state_id UUID NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_city_municipalities_state FOREIGN KEY (state_id) REFERENCES state_regions (id) ON DELETE RESTRICT
);

